"""Pede a um modelo multimodal (Gemini via OpenRouter) a descrição do movimento de um vídeo de UI: O QUE se mexe e COMO.

    uv run analisar_video.py <video.mp4> <saida.md> [--regioes regioes.json] [--modelo google/gemini-3.1-flash-lite]
                             [--lento 4] [--comparar outro.mp4]

- O Gemini olha o vídeo a ~1 quadro/s: por isso o vídeo é desacelerado (--lento 4 → ~4 quadros/s efetivos) e os
  tempos da resposta são divididos de volta. O tempo FINO vem do mapa_movimento.py; daqui vem o caráter do movimento.
- Com --regioes, a lista de regiões do mapa de movimento vai no prompt (o modelo descreve cada uma pelo id).
- Com --comparar, manda os dois vídeos (referência e recriação) e pede as diferenças de ritmo e caráter.
- Custo: centavos ou menos. Chave OPENROUTER_API_KEY do ambiente, de .env no cwd ou de ~/.env (nunca é impressa).
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import subprocess
import sys
import tempfile
import urllib.error
import urllib.request
from pathlib import Path

API = 'https://openrouter.ai/api/v1/chat/completions'

PROMPT = """You are a senior motion designer analysing a short screen recording of an animated app UI (no audio).
The clip you receive was slowed down {lento}x: it lasts {dur_lento:.0f} s, but the real animation lasts {dur:.1f} s. Report every time
in REAL seconds (0 to {dur:.1f}): real = time in the clip / {lento}.

Describe the motion so a front-end developer can rebuild it in code (CSS/SVG/Canvas/Three.js). For EVERY element that moves:
- element: what it is (e.g. "connector beam from the core to the 'Reels Editor' node", "robot eye", "HUD ring")
- motion: what happens visually (pulse, glow, light travelling along a path, rotation, flicker, scroll, scale…)
- timing: start/end in real seconds, duration, whether it loops and its period
- easing/character: smooth/snappy/organic, ease-in/out, intensity
- sequence: what it is synchronised with (e.g. "the node ring flares when the beam arrives")
Also list elements that clearly stay still, and anything that looks like a generation artefact (text that morphs, labels that change,
objects appearing) — those must NOT be reproduced.
{regioes}
Answer in Portuguese (pt-BR), as a markdown table (elemento | movimento | tempo | curva/caráter | sincronia) followed by a short
paragraph on the overall rhythm/mood and a bullet list of artefacts."""

PROMPT_COMPARAR = """Two short screen recordings of the same app UI (no audio), both slowed down {lento}x. VIDEO 1 is the motion
REFERENCE (generated by a video model). VIDEO 2 is the HTML RECREATION. Ignore any text/label changes in VIDEO 1 (generation artefacts).
Compare only MOTION: for each animated element say whether VIDEO 2 matches the reference in timing, rhythm, intensity and character,
and what to change (e.g. "the eye pulse is ~2x too fast", "the beam should travel slower and leave a trail"). Also list motion present in
one and missing in the other. Answer in Portuguese (pt-BR), as a markdown table (elemento | referência | recriação | ajuste) plus a verdict."""


def chave() -> str:
    if os.environ.get('OPENROUTER_API_KEY'):
        return os.environ['OPENROUTER_API_KEY']
    for env in (Path.cwd() / '.env', Path.home() / '.env'):
        if env.exists():
            for linha in env.read_text(encoding='utf-8').splitlines():
                if linha.strip().startswith('OPENROUTER_API_KEY='):
                    return linha.split('=', 1)[1].strip().strip('"').strip("'")
    sys.exit('ERRO: defina OPENROUTER_API_KEY (ambiente, .env ou ~/.env).')


def lento_b64(video: Path, fator: float) -> str:
    with tempfile.TemporaryDirectory() as d:
        out = Path(d) / 'lento.mp4'
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', str(video), '-vf', f'setpts={fator}*PTS,scale=960:-2',
                        '-an', '-c:v', 'libx264', '-crf', '26', '-preset', 'veryfast', str(out)], check=True)
        return base64.b64encode(out.read_bytes()).decode()


def duracao(video: Path) -> float:
    return float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(video)],
                                capture_output=True, text=True).stdout.strip())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('video')
    ap.add_argument('saida')
    ap.add_argument('--regioes')
    ap.add_argument('--comparar', help='vídeo da recriação (modo comparação)')
    ap.add_argument('--modelo', default='google/gemini-3.8-flash')
    ap.add_argument('--lento', type=float, default=None, help='desaceleração (padrão: 4 na análise, 8 na comparação)')
    a = ap.parse_args()

    partes = []
    if a.lento is None:
        a.lento = 8 if a.comparar else 4   # dois vídeos a ~1 quadro/s: eventos de 0,5 s somem se não desacelerar mais
    if a.comparar:
        texto = PROMPT_COMPARAR.format(lento=a.lento)
        videos = [Path(a.video), Path(a.comparar)]
    else:
        reg = ''
        if a.regioes:
            dados = json.loads(Path(a.regioes).read_text(encoding='utf-8'))
            linhas = [f"- {r['id']}: box x={r['caixa'][0]} y={r['caixa'][1]} w={r['caixa'][2]} h={r['caixa'][3]} (in a "
                      f"{dados['largura_ref']}px-wide frame), active at {r['janelas_ativas_s'][:3]} s" for r in dados['regioes'][:20]]
            reg = '\nA pixel-motion analysis found these moving regions (use their ids when they match an element):\n' + '\n'.join(linhas)
        dur = duracao(Path(a.video))
        texto = PROMPT.format(lento=a.lento, regioes=reg, dur=dur, dur_lento=dur * a.lento)
        videos = [Path(a.video)]
    partes.append({'type': 'text', 'text': texto})
    for v in videos:
        partes.append({'type': 'video_url', 'video_url': {'url': f'data:video/mp4;base64,{lento_b64(v, a.lento)}', 'processing': 'static'}})

    corpo = {'model': a.modelo, 'messages': [{'role': 'user', 'content': partes}]}
    req = urllib.request.Request(API, data=json.dumps(corpo).encode(), method='POST', headers={
        'Authorization': f'Bearer {chave()}', 'Content-Type': 'application/json', 'X-Title': 'video2html'})
    try:
        with urllib.request.urlopen(req, timeout=300) as r:
            dados = json.loads(r.read())
    except urllib.error.HTTPError as e:
        sys.exit(f'OpenRouter HTTP {e.code}: {e.read().decode(errors="replace")[:600]}')
    resposta = dados['choices'][0]['message']['content']
    custo = (dados.get('usage') or {}).get('cost')
    cab = f"<!-- {a.modelo} · {'comparação' if a.comparar else 'análise'} · lento {a.lento}x · custo ${custo} -->\n\n"
    Path(a.saida).write_text(cab + resposta, encoding='utf-8')
    print(f'{a.saida} · ${custo}')


if __name__ == '__main__':
    main()
