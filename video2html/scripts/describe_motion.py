"""Ask a multimodal model (Gemini via OpenRouter) to describe the motion of a UI video: WHAT moves and HOW.

    uv run describe_motion.py <video.mp4> <out.md> [--regions regions.json] [--slow 4] [--model google/gemini-3.8-flash]
    uv run describe_motion.py <reference.mp4> <out.md> --compare <recreation.mp4>

- The model sees video at ~1 frame/s, so the clip is slowed down (--slow) and the times in the answer are converted
  back to real seconds. Fine timing comes from motion_map.py; this gives the character of the motion.
- --regions passes motion_map.py's regions so the model can refer to them by id.
- --compare sends both videos and asks for the motion differences (timing, rhythm, intensity).
- Costs cents. Key: OPENROUTER_API_KEY from the environment, ./.env or ~/.env (never printed).
- The model misses short events and sometimes claims something does not happen: check frames before acting on it.
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import subprocess
import sys
import tempfile
import urllib.error
import urllib.request
from pathlib import Path

API = 'https://openrouter.ai/api/v1/chat/completions'

PROMPT = """You are a senior motion designer analysing a short screen recording of an animated app UI (no audio).
The clip was slowed down {slow}x: it lasts {dur_slow:.0f} s, but the real animation lasts {dur:.1f} s. Report every time
in REAL seconds (0 to {dur:.1f}): real = time in the clip / {slow}.

Describe the motion so a front-end developer can rebuild it in code (CSS/SVG/Canvas/Three.js). For EVERY element that moves:
- element: what it is
- motion: what happens visually (pulse, glow, light travelling along a path, rotation, flicker, scroll, scale…)
- timing: start/end in real seconds, duration, whether it loops and its period
- easing/character: smooth/snappy/organic, ease-in/out, intensity
- sequence: what it is synchronised with
Also list elements that clearly stay still, and anything that looks like a generation artefact (text that morphs, labels
that change, objects appearing) — those must NOT be reproduced.
{regions}
Answer as a markdown table (element | motion | timing | character | sync), then a short paragraph on the overall rhythm
and mood, then a bullet list of artefacts."""

PROMPT_COMPARE = """Two short screen recordings of the same app UI (no audio), both slowed down {slow}x. VIDEO 1 is the motion
REFERENCE (generated by a video model). VIDEO 2 is the HTML RECREATION. Ignore text/label changes in VIDEO 1 (artefacts).
Compare only MOTION: for each animated element say whether VIDEO 2 matches the reference in timing, rhythm, intensity
and character, and what to change. List motion present in one and missing in the other. Answer as a markdown table
(element | reference | recreation | change) plus a verdict."""


def key() -> str:
    if os.environ.get('OPENROUTER_API_KEY'):
        return os.environ['OPENROUTER_API_KEY']
    for env in (Path.cwd() / '.env', Path.home() / '.env'):
        if env.exists():
            for line in env.read_text(encoding='utf-8').splitlines():
                if line.strip().startswith('OPENROUTER_API_KEY='):
                    return line.split('=', 1)[1].strip().strip('"').strip("'")
    sys.exit('ERROR: set OPENROUTER_API_KEY (environment, .env or ~/.env).')


def slow_b64(video: Path, factor: float) -> str:
    with tempfile.TemporaryDirectory() as d:
        out = Path(d) / 'slow.mp4'
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', str(video), '-vf', f'setpts={factor}*PTS,scale=960:-2',
                        '-an', '-c:v', 'libx264', '-crf', '26', '-preset', 'veryfast', str(out)], check=True)
        return base64.b64encode(out.read_bytes()).decode()


def duration(video: Path) -> float:
    return float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(video)],
                                capture_output=True, text=True).stdout.strip())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('video')
    ap.add_argument('out')
    ap.add_argument('--regions')
    ap.add_argument('--compare', help='video of the recreation (comparison mode)')
    ap.add_argument('--model', default='google/gemini-3.8-flash')
    ap.add_argument('--slow', type=float, default=None, help='slow-down factor (default: 4 to analyse, 8 to compare)')
    a = ap.parse_args()
    if a.slow is None:
        a.slow = 8 if a.compare else 4
    if a.compare:
        text = PROMPT_COMPARE.format(slow=a.slow)
        videos = [Path(a.video), Path(a.compare)]
    else:
        reg = ''
        if a.regions:
            data = json.loads(Path(a.regions).read_text(encoding='utf-8'))
            lines = [f"- {r['id']}: box x={r['box'][0]} y={r['box'][1]} w={r['box'][2]} h={r['box'][3]} (in a {data['ref_width']}px-wide "
                     f"frame), active at {r['active_windows_s'][:3]} s" for r in data['regions'][:20]]
            reg = '\nA pixel-motion analysis found these moving regions (use their ids when they match an element):\n' + '\n'.join(lines)
        dur = duration(Path(a.video))
        text = PROMPT.format(slow=a.slow, regions=reg, dur=dur, dur_slow=dur * a.slow)
        videos = [Path(a.video)]
    parts: list[dict] = [{'type': 'text', 'text': text}]
    for v in videos:
        parts.append({'type': 'video_url', 'video_url': {'url': f'data:video/mp4;base64,{slow_b64(v, a.slow)}', 'processing': 'static'}})
    body = {'model': a.model, 'messages': [{'role': 'user', 'content': parts}]}
    req = urllib.request.Request(API, data=json.dumps(body).encode(), method='POST', headers={
        'Authorization': f'Bearer {key()}', 'Content-Type': 'application/json', 'X-Title': 'video2html'})
    try:
        with urllib.request.urlopen(req, timeout=300) as r:
            data = json.loads(r.read())
    except urllib.error.HTTPError as e:
        sys.exit(f'OpenRouter HTTP {e.code}: {e.read().decode(errors="replace")[:600]}')
    answer = data['choices'][0]['message']['content']
    cost = (data.get('usage') or {}).get('cost')
    head = f"<!-- {a.model} · {'comparison' if a.compare else 'analysis'} · slow {a.slow}x · cost ${cost} -->\n\n"
    Path(a.out).write_text(head + answer, encoding='utf-8')
    print(f'{a.out} · ${cost}')


if __name__ == '__main__':
    main()
